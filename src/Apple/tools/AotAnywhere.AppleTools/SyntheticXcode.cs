namespace AotAnywhere.AppleTools;

/// <summary>
/// Writes a stand-in Xcode folder for builds without Xcode: the handful of plists the workload
/// reads to locate an Xcode and its iOS SDKs and to fill the app's <c>DT*</c> Info.plist keys,
/// containing only version numbers - those the workload itself asks for
/// (<c>RecommendedXcodeVersion</c>, and the iOS SDK version its packs target). No Apple file is
/// used or copied: headers come from <see cref="ObjCShims"/> and linker stubs from the package's
/// sysroot (<see cref="IosStubs"/>), so nothing reads the SDK folders' contents.
/// </summary>
public static class SyntheticXcode
{
    /// <summary>Marks a folder as generated here (and so safe to rewrite).</summary>
    public const string Marker = "AotAnywhere.synthetic";

    static readonly string[] Platforms = ["iPhoneOS", "iPhoneSimulator"];

    public static void Write(string xcodeApp, string xcodeVersion, string sdkVersion)
    {
        string contents = Path.Combine(xcodeApp, "Contents");
        string developer = Path.Combine(contents, "Developer");
        string build = "AotAnywhere";

        WritePlist(Path.Combine(contents, "Info.plist"), new()
        {
            ["CFBundleIdentifier"] = "com.apple.dt.Xcode",
            ["CFBundleShortVersionString"] = xcodeVersion,
            ["CFBundleVersion"] = xcodeVersion,
            ["DTXcode"] = XcodeVersionCode(xcodeVersion),
            ["DTXcodeBuild"] = build,
        });
        WritePlist(Path.Combine(contents, "version.plist"), new()
        {
            ["CFBundleShortVersionString"] = xcodeVersion,
            ["CFBundleVersion"] = xcodeVersion,
            ["ProductBuildVersion"] = build,
        });
        // The workload's Xcode locator requires an Xcode executable and a developer usr/bin.
        Directory.CreateDirectory(Path.Combine(contents, "MacOS"));
        File.WriteAllBytes(Path.Combine(contents, "MacOS", "Xcode"), []);
        Directory.CreateDirectory(Path.Combine(developer, "usr", "bin"));

        foreach (var platform in Platforms)
        {
            string platformDir = Path.Combine(developer, "Platforms", platform + ".platform");
            string lower = platform.ToLowerInvariant();
            // The workload copies AdditionalInfo's DT* values into the app's Info.plist.
            var dt = new Dictionary<string, object>(StringComparer.Ordinal)
            {
                ["DTCompiler"] = "com.apple.compilers.llvm.clang.1_0",
                ["DTPlatformBuild"] = build,
                ["DTPlatformName"] = lower,
                ["DTPlatformVersion"] = sdkVersion,
                ["DTSDKBuild"] = build,
                ["DTXcode"] = XcodeVersionCode(xcodeVersion),
                ["DTXcodeBuild"] = build,
            };
            WritePlist(Path.Combine(platformDir, "Info.plist"), new()
            {
                ["CFBundleIdentifier"] = "com.apple.platform." + lower,
                ["CFBundleName"] = platform,
                ["CFBundleShortVersionString"] = sdkVersion,
                ["AdditionalInfo"] = dt,
            });
            string sdk = Path.Combine(platformDir, "Developer", "SDKs", platform + sdkVersion + ".sdk");
            WritePlist(Path.Combine(sdk, "SDKSettings.plist"), new()
            {
                ["CanonicalName"] = lower + sdkVersion,
                ["DisplayName"] = $"{(platform == "iPhoneOS" ? "iOS" : "Simulator - iOS")} {sdkVersion}",
                ["Version"] = sdkVersion,
                ["MaximumDeploymentTarget"] = sdkVersion + ".99",
                ["MinimalDisplayName"] = sdkVersion,
                ["DefaultDeploymentTarget"] = sdkVersion,
                ["IsBaseSDK"] = "YES",
                ["DefaultProperties"] = new Dictionary<string, object>(StringComparer.Ordinal) { ["PLATFORM_NAME"] = lower },
            });
            WritePlist(Path.Combine(sdk, "System", "Library", "CoreServices", "SystemVersion.plist"), new()
            {
                ["ProductName"] = "iPhone OS",
                ["ProductVersion"] = sdkVersion,
                ["ProductBuildVersion"] = build,
            });
            // The template the workload starts an app's entitlements from (variables it substitutes):
            // the application identifier and its own keychain group, both documented defaults.
            WritePlist(Path.Combine(sdk, "Entitlements.plist"), new()
            {
                ["application-identifier"] = "$(AppIdentifierPrefix)$(CFBundleIdentifier)",
                ["keychain-access-groups"] = new List<object> { "$(AppIdentifierPrefix)$(CFBundleIdentifier)" },
            });
            Directory.CreateDirectory(Path.Combine(sdk, "usr", "include"));
            Directory.CreateDirectory(Path.Combine(sdk, "System", "Library", "Frameworks"));
        }
        File.WriteAllText(Path.Combine(xcodeApp, Marker), $"Generated by AotAnywhere for Xcode {xcodeVersion} / iOS SDK {sdkVersion}. Contains no Apple files.\n");
    }

    // "27.0" -> "2700", "16.4" -> "1640" (the DTXcode form).
    static string XcodeVersionCode(string version)
    {
        var v = Version.Parse(version.Contains('.') ? version : version + ".0");
        return $"{v.Major}{Math.Max(v.Minor, 0)}{Math.Max(v.Build, 0)}".PadLeft(4, '0');
    }

    static void WritePlist(string path, Dictionary<string, object> value)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllBytes(path, Plist.WriteXml(value));
    }
}
